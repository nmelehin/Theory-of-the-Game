const IMPORTANCE_LABEL: Record<Importance, string> = {
  core: "Ключевой",
  major: "Важный",
  supporting: "Вспомогательный",
};

function importanceColor(importance: Importance, theme: ReturnType<typeof useHostTheme>) {
  switch (importance) {
    case "core":
      return theme.accent.primary;
    case "major":
      return theme.text.link;
    default:
      return theme.text.tertiary;
  }
}

// ─── Схема восхождения ──────────────────────────────────────────────────────

function AscentSvg({
  selected,
  onSelect,
}: {
  selected: number;
  onSelect: (n: number) => void;
}) {
  const theme = useHostTheme();

  const width = 640;
  const rowH = 64;
  const gap = 14;
  const padTop = 56;
  const padBottom = 24;
  // Чертоги вложены один в другой: чем выше, тем уже прямоугольник.
  const height = padTop + PALACES.length * (rowH + gap) - gap + padBottom;

  return (
    <svg
      viewBox={`0 0 ${width} ${height}`}
      style={{ width: "100%", maxHeight: 620, display: "block" }}
      role="img"
      aria-label="Восхождение по семи чертогам к Престолу Славы"
    >
      <text
        x={width / 2}
        y={26}
        textAnchor="middle"
        fill={theme.text.tertiary}
        fontSize={11}
        letterSpacing={2}
      >
        АРАВОТ — СЕДЬМОЕ НЕБО
      </text>
      <text
        x={width / 2}
        y={42}
        textAnchor="middle"
        fill={theme.text.quaternary}
        fontSize={10}
      >
        ▲ направление восхождения: от первых врат к Престолу
      </text>

      {PALACES.map((p, i) => {
        // Седьмой чертог сверху, первый снизу.
        const rank = PALACES.length - p.n; // 0 для седьмого
        const y = padTop + rank * (rowH + gap);
        const inset = rank === 0 ? 150 : 20 + (PALACES.length - 1 - rank) * 22;
        const x = inset;
        const w = width - inset * 2;
        const isSelected = p.n === selected;
        const isThrone = p.n === 7;
        const stroke = isThrone ? theme.accent.primary : theme.stroke.primary;

        return (
          <g
            key={p.n}
            style={{ cursor: "pointer" }}
            onClick={() => onSelect(p.n)}
            role="button"
            aria-label={p.title}
          >
            <rect
              x={x}
              y={y}
              width={w}
              height={rowH}
              rx={isThrone ? 14 : 8}
              fill={isSelected ? theme.fill.secondary : theme.bg.elevated}
              stroke={isSelected ? theme.accent.primary : stroke}
              strokeWidth={isSelected ? 2 : isThrone ? 1.5 : 1}
              strokeDasharray={isThrone && !isSelected ? "5 3" : undefined}
            />
            <text
              x={width / 2}
              y={y + 24}
              textAnchor="middle"
              fill={isSelected ? theme.text.primary : theme.text.secondary}
              fontSize={13}
              fontWeight={isThrone ? 700 : 500}
            >
              {isThrone ? "✦ " : ""}
              {p.title}
              {isThrone ? " · Престол Славы" : ""}
            </text>
            <text
              x={width / 2}
              y={y + 44}
              textAnchor="middle"
              fill={theme.text.quaternary}
              fontSize={10}
            >
              {p.gate}
            </text>

            {i < PALACES.length - 1 ? (
              <text
                x={width / 2}
                y={y + rowH + gap - 3}
                textAnchor="middle"
                fill={theme.text.quaternary}
                fontSize={9}
              >
                — врата · стражи справа и слева · две печати —
              </text>
            ) : null}
          </g>
        );
      })}
    </svg>
  );
}

// ─── Майндмэп SVG ───────────────────────────────────────────────────────────

function MindMapSvg({
  nodes,
  edges,
  selectedId,
  onSelect,
}: {
  nodes: MindNode[];
  edges: Array<{ from: string; to: string }>;
  selectedId: string;
  onSelect: (id: string) => void;
}) {
  const theme = useHostTheme();

  const layout = useMemo(
    () =>
      computeDAGLayout({
        nodes: nodes.map((n) => ({ id: n.id })),
        edges,
        direction: "vertical",
        nodeWidth: 210,
        nodeHeight: 44,
        rankGap: 68,
        nodeGap: 28,
        padding: 32,
      }),
    [nodes, edges],
  );

  const nodeMap = useMemo(() => new Map(nodes.map((n) => [n.id, n])), [nodes]);

  return (
    <svg
      viewBox={`0 0 ${layout.width} ${layout.height}`}
      style={{ width: "100%", maxHeight: 560, display: "block" }}
      role="img"
      aria-label="Майндмэп: традиция Меркавы и Хейхалот"
    >
      {layout.edges.map((edge) => (
        <line
          key={`${edge.from}-${edge.to}`}
          x1={edge.sourceX}
          y1={edge.sourceY}
          x2={edge.targetX}
          y2={edge.targetY}
          stroke={theme.stroke.secondary}
          strokeWidth={1.5}
          strokeDasharray={edge.isBackEdge ? "4 3" : undefined}
        />
      ))}

      {layout.nodes.map((ln) => {
        const node = nodeMap.get(ln.id);
        if (!node) return null;
        const isSelected = ln.id === selectedId;
        const color = importanceColor(node.importance, theme);
        const w = 210;
        const h = 44;

        return (
          <g
            key={ln.id}
            style={{ cursor: "pointer" }}
            onClick={() => onSelect(ln.id)}
            role="button"
            aria-label={node.label}
          >
            <rect
              x={ln.x}
              y={ln.y}
              width={w}
              height={h}
              rx={6}
              fill={isSelected ? theme.fill.secondary : theme.bg.elevated}
              stroke={isSelected ? color : theme.stroke.primary}
              strokeWidth={isSelected ? 2 : 1}
            />
            <text
              x={ln.x + w / 2}
              y={ln.y + h / 2}
              textAnchor="middle"
              dominantBaseline="middle"
              fill={isSelected ? theme.text.primary : theme.text.secondary}
              fontSize={11}
              fontWeight={node.importance === "core" ? 600 : 400}
            >
              {node.label.length > 30 ? node.label.slice(0, 28) + "…" : node.label}
            </text>
          </g>
        );
      })}
    </svg>
  );
}

function NodeDetail({ node }: { node: MindNode }) {
  return (
    <Stack gap={12}>
      <Row gap={8} align="center" wrap>
        <Pill tone={node.importance === "core" ? "info" : "neutral"} size="sm">
          {IMPORTANCE_LABEL[node.importance]}
        </Pill>
      </Row>

      <Text weight="semibold">{node.summary}</Text>

      <Text size="small" tone="secondary" style={{ lineHeight: 1.65 }}>
        {node.detail}
      </Text>
    </Stack>
  );
}

