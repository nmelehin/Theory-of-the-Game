function importanceColor(importance: Importance, theme: ReturnType<typeof useHostTheme>) {
  switch (importance) {
    case "core":
      return theme.accent.primary;
    case "major":
      return theme.text.link;
    default:
      return theme.text.tertiary;
  }
}

function MindMapSvg({
  nodes,
  edges,
  selectedId,
  onSelect,
}: {
  nodes: MindNode[];
  edges: Array<{ from: string; to: string }>;
  selectedId: string;
  onSelect: (id: string) => void;
}) {
  const theme = useHostTheme();

  const layout = useMemo(
    () =>
      computeDAGLayout({
        nodes: nodes.map((n) => ({ id: n.id })),
        edges,
        direction: "vertical",
        nodeWidth: 200,
        nodeHeight: 44,
        rankGap: 72,
        nodeGap: 32,
        padding: 32,
      }),
    [nodes, edges],
  );

  const nodeMap = useMemo(() => new Map(nodes.map((n) => [n.id, n])), [nodes]);

  return (
    <svg
      viewBox={`0 0 ${layout.width} ${layout.height}`}
      style={{ width: "100%", maxHeight: 520, display: "block" }}
      role="img"
      aria-label="Mind map: Morals and Dogma"
    >
      {layout.edges.map((edge) => {
        const isBack = edge.isBackEdge;
        return (
          <line
            key={`${edge.from}-${edge.to}`}
            x1={edge.sourceX}
            y1={edge.sourceY}
            x2={edge.targetX}
            y2={edge.targetY}
            stroke={theme.stroke.secondary}
            strokeWidth={1.5}
            strokeDasharray={isBack ? "4 3" : undefined}
          />
        );
      })}

      {layout.nodes.map((ln) => {
        const node = nodeMap.get(ln.id);
        if (!node) return null;
        const isSelected = ln.id === selectedId;
        const color = importanceColor(node.importance, theme);
        const w = 200;
        const h = 44;

        return (
          <g
            key={ln.id}
            style={{ cursor: "pointer" }}
            onClick={() => onSelect(ln.id)}
            role="button"
            aria-label={node.label}
          >
            <rect
              x={ln.x}
              y={ln.y}
              width={w}
              height={h}
              rx={6}
              fill={isSelected ? theme.fill.secondary : theme.bg.elevated}
              stroke={isSelected ? color : theme.stroke.primary}
              strokeWidth={isSelected ? 2 : 1}
            />
            <text
              x={ln.x + w / 2}
              y={ln.y + h / 2 - (node.time ? 5 : 0)}
              textAnchor="middle"
              dominantBaseline="middle"
              fill={isSelected ? theme.text.primary : theme.text.secondary}
              fontSize={11}
              fontWeight={node.importance === "core" ? 600 : 400}
            >
              {node.label.length > 28 ? node.label.slice(0, 26) + "…" : node.label}
            </text>
            {node.time ? (
              <text
                x={ln.x + w / 2}
                y={ln.y + h / 2 + 12}
                textAnchor="middle"
                fill={theme.text.quaternary}
                fontSize={9}
              >
                {node.time}
              </text>
            ) : null}
          </g>
        );
      })}
    </svg>
  );
}

function NodeDetail({ node }: { node: MindNode }) {
  const theme = useHostTheme();
  const color = importanceColor(node.importance, theme);

  return (
    <Stack gap={12}>
      <Row gap={8} align="center" wrap>
        <Pill tone={node.importance === "core" ? "info" : "neutral"} size="sm">
          {IMPORTANCE_LABEL[node.importance]}
        </Pill>
        {node.time ? (
          <Text size="small" tone="tertiary">
            {node.time}
          </Text>
        ) : null}
      </Row>

      <Text weight="semibold">{node.summary}</Text>

      <Text size="small" tone="secondary" style={{ lineHeight: 1.65 }}>
        {node.detail}
      </Text>

      {node.importance === "core" ? (
        <Card variant="borderless">
          <CardBody>
            <Text size="small" tone="secondary" style={{ lineHeight: 1.6 }}>
              <span style={{ color: color, fontWeight: 500 }}>Почему это центрально: </span>
              {node.id === "root" &&
                "Все прочие узлы — либо контекст создания книги, либо её внутренние разделы, либо линии её рецепции. Понимание жанра («чтения к градусам», а не догматический катехизис) снимает половину типичных недоразумений вокруг текста."}
              {node.id === "author" &&
                "Без фигуры Пайка книга непонятна: это не анонимная доктрина ордена, а авторский проект реформатора, который переписал ритуалы устава и снабдил их философским комментарием."}
              {node.id === "structure" &&
                "Композиция «глава = градус» — ключ к чтению: книга не линейный трактат, а лестница, где каждая ступень предполагает опыт соответствующего посвящения."}
              {node.id === "royalsecret" &&
                "Равновесие — итоговая формула всей книги: к ней стягиваются и «сила без управления» первой главы, и пары противоположностей каббалистических глав, и этика меры в политических рассуждениях."}
              {node.id === "symbols" &&
                "Учение о символе объясняет и метод самой книги, и её скандальную репутацию: тот же пассаж о «сокрытии тайн» служит аргументом и апологетам, и критикам масонства."}
            </Text>
          </CardBody>
        </Card>
      ) : null}
    </Stack>
  );
}

