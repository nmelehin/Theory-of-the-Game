function importanceColor(importance: Importance, theme: ReturnType<typeof useHostTheme>) {
  switch (importance) {
    case "core":
      return theme.accent.primary;
    case "major":
      return theme.text.link;
    default:
      return theme.text.tertiary;
  }
}

function MindMapSvg({
  nodes,
  edges,
  selectedId,
  onSelect,
}: {
  nodes: MindNode[];
  edges: Array<{ from: string; to: string }>;
  selectedId: string;
  onSelect: (id: string) => void;
}) {
  const theme = useHostTheme();

  const layout = useMemo(
    () =>
      computeDAGLayout({
        nodes: nodes.map((n) => ({ id: n.id })),
        edges,
        direction: "vertical",
        nodeWidth: 200,
        nodeHeight: 44,
        rankGap: 72,
        nodeGap: 32,
        padding: 32,
      }),
    [nodes, edges],
  );

  const nodeMap = useMemo(() => new Map(nodes.map((n) => [n.id, n])), [nodes]);

  return (
    <svg
      viewBox={`0 0 ${layout.width} ${layout.height}`}
      style={{ width: "100%", maxHeight: 520, display: "block" }}
      role="img"
      aria-label="Mind map: Окончательное путешествие Роберта Монро"
    >
      {layout.edges.map((edge) => {
        const isBack = edge.isBackEdge;
        return (
          <line
            key={`${edge.from}-${edge.to}`}
            x1={edge.sourceX}
            y1={edge.sourceY}
            x2={edge.targetX}
            y2={edge.targetY}
            stroke={theme.stroke.secondary}
            strokeWidth={1.5}
            strokeDasharray={isBack ? "4 3" : undefined}
          />
        );
      })}

      {layout.nodes.map((ln) => {
        const node = nodeMap.get(ln.id);
        if (!node) return null;
        const isSelected = ln.id === selectedId;
        const color = importanceColor(node.importance, theme);
        const w = 200;
        const h = 44;

        return (
          <g
            key={ln.id}
            style={{ cursor: "pointer" }}
            onClick={() => onSelect(ln.id)}
            role="button"
            aria-label={node.label}
          >
            <rect
              x={ln.x}
              y={ln.y}
              width={w}
              height={h}
              rx={6}
              fill={isSelected ? theme.fill.secondary : theme.bg.elevated}
              stroke={isSelected ? color : theme.stroke.primary}
              strokeWidth={isSelected ? 2 : 1}
            />
            <text
              x={ln.x + w / 2}
              y={ln.y + h / 2 - (node.time ? 5 : 0)}
              textAnchor="middle"
              dominantBaseline="middle"
              fill={isSelected ? theme.text.primary : theme.text.secondary}
              fontSize={11}
              fontWeight={node.importance === "core" ? 600 : 400}
            >
              {node.label.length > 28 ? node.label.slice(0, 26) + "…" : node.label}
            </text>
            {node.time ? (
              <text
                x={ln.x + w / 2}
                y={ln.y + h / 2 + 12}
                textAnchor="middle"
                fill={theme.text.quaternary}
                fontSize={9}
              >
                {node.time}
              </text>
            ) : null}
          </g>
        );
      })}
    </svg>
  );
}

function NodeDetail({ node }: { node: MindNode }) {
  const theme = useHostTheme();
  const color = importanceColor(node.importance, theme);

  return (
    <Stack gap={12}>
      <Row gap={8} align="center" wrap>
        <Pill tone={node.importance === "core" ? "info" : "neutral"} size="sm">
          {IMPORTANCE_LABEL[node.importance]}
        </Pill>
        {node.time ? (
          <Text size="small" tone="tertiary">
            {node.time} из 19 глав
          </Text>
        ) : null}
      </Row>

      <Text weight="semibold">{node.summary}</Text>

      <Text size="small" tone="secondary" style={{ lineHeight: 1.65 }}>
        {node.detail}
      </Text>

      {node.importance === "core" ? (
        <Card variant="borderless">
          <CardBody>
            <Text size="small" tone="secondary" style={{ lineHeight: 1.6 }}>
              <span style={{ color: color, fontWeight: 500 }}>Почему это центрально: </span>
              {node.id === "root" &&
                "Это не третий сборник приключений, а замковый камень трилогии: две первые книги дали материал, эта — маршрут, метод передачи и ответ на вопрос о цели. Без неё карта Монро остаётся коллекцией эпизодов."}
              {node.id === "knowns" &&
                "Различение убеждений и Истин — эпистемология всей книги. Оно объясняет и метод Монро (только личный опыт), и устройство посмертия (застревают именно в убеждениях), и смысл института (дать опыт, а не доктрину)."}
              {node.id === "interstate" &&
                "Магистраль — несущая метафора: она превращает разрозненные внетелесные эпизоды в связную географию с маршрутом, ориентирами и правилами движения. Всё остальное в книге — путевые заметки с этой дороги."}
              {node.id === "i-there" &&
                "Открытие Я-Там меняет сам субъект повествования: путешествует не «Роберт Монро», а разведчик кластерного сверхсознания. Отсюда следуют и разгадка ИНСПЕКов, и невозможность страха, и постановка задачи Базиса."}
              {node.id === "emitter" &&
                "Предел маршрута задаёт цель: отказ у Апертуры — «ты неполон, где твои дары?» — единственное место книги, где Монро получает прямое указание, чего не хватает. Вся финальная часть — расшифровка этого отказа."}
              {node.id === "basic" &&
                "Базис — точка схождения всех линий: спасение застрявших, институт, книги и само Я-Там оказываются частями одной задачи собирания. Это итоговый ответ трилогии на вопрос о смысле человеческого существования."}
            </Text>
          </CardBody>
        </Card>
      ) : null}
    </Stack>
  );
}

