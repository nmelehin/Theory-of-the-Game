const STORY_IDS = STORIES.map((s) => s.id);

function SunWheel({
  stories,
  selectedId,
  onSelect,
}: {
  stories: Story[];
  selectedId: string;
  onSelect: (id: string) => void;
}) {
  const theme = useHostTheme();

  const size = 780;
  const cx = size / 2;
  const cy = size / 2;

  const positions = useMemo(() => {
    return stories.map((story, i) => {
      const angle = (i / stories.length) * Math.PI * 2 - Math.PI / 2;
      // Чередуем радиус, чтобы подписи соседних узлов не пересекались
      const r = i % 2 === 0 ? 225 : 300;
      return {
        id: story.id,
        x: cx + r * Math.cos(angle),
        y: cy + r * Math.sin(angle),
      };
    });
  }, [stories, cx, cy]);

  const nodeW = 128;
  const nodeH = 40;

  return (
    <svg
      viewBox={`0 0 ${size} ${size}`}
      style={{ width: "100%", maxHeight: 560, display: "block" }}
      role="img"
      aria-label="Солнечное колесо: 15 историй вокруг одного героя — Солнца"
    >
      {positions.map((p) => (
        <line
          key={`ray-${p.id}`}
          x1={cx}
          y1={cy}
          x2={p.x}
          y2={p.y}
          stroke={p.id === selectedId ? theme.accent.primary : theme.stroke.secondary}
          strokeWidth={p.id === selectedId ? 2 : 1}
        />
      ))}

      <circle cx={cx} cy={cy} r={92} fill={theme.bg.elevated} stroke={theme.accent.primary} strokeWidth={2} />
      <circle cx={cx} cy={cy} r={78} fill="none" stroke={theme.stroke.secondary} strokeWidth={1} strokeDasharray="3 4" />
      <text x={cx} y={cy - 10} textAnchor="middle" fill={theme.text.primary} fontSize={17} fontWeight={700}>
        СОЛНЦЕ
      </text>
      <text x={cx} y={cy + 12} textAnchor="middle" fill={theme.text.tertiary} fontSize={11}>
        герой одной и той же
      </text>
      <text x={cx} y={cy + 27} textAnchor="middle" fill={theme.text.tertiary} fontSize={11}>
        «величайшей истории»
      </text>

      {positions.map((p, i) => {
        const story = stories[i];
        const isSelected = story.id === selectedId;
        return (
          <g
            key={story.id}
            style={{ cursor: "pointer" }}
            onClick={() => onSelect(story.id)}
            role="button"
            aria-label={`${story.name} (${story.culture})`}
          >
            <rect
              x={p.x - nodeW / 2}
              y={p.y - nodeH / 2}
              width={nodeW}
              height={nodeH}
              rx={20}
              fill={isSelected ? theme.fill.secondary : theme.bg.elevated}
              stroke={isSelected ? theme.accent.primary : theme.stroke.primary}
              strokeWidth={isSelected ? 2 : 1}
            />
            <text
              x={p.x}
              y={p.y - 3}
              textAnchor="middle"
              dominantBaseline="middle"
              fill={isSelected ? theme.text.primary : theme.text.secondary}
              fontSize={13}
              fontWeight={isSelected ? 700 : 500}
            >
              {story.name}
            </text>
            <text
              x={p.x}
              y={p.y + 12}
              textAnchor="middle"
              dominantBaseline="middle"
              fill={theme.text.quaternary}
              fontSize={9}
            >
              {story.culture}
            </text>
          </g>
        );
      })}
    </svg>
  );
}

